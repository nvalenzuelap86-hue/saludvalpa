/**
 * Obtiene todos los ejercicios precargados
 */
export function obtenerEjerciciosPrecargados(): EjercicioPrecargado[] {
  return [
    ...ejerciciosMovilidad,
    ...ejerciciosFuerza,
    ...ejerciciosEquilibrio,
    ...ejerciciosEstiramiento,
    ...ejerciciosCardio,
  ];
}

/**
 * Obtiene ejercicios por categoría
 */
export function obtenerEjerciciosPorCategoria(categoria: CategoriaEjercicio): EjercicioPrecargado[] {
  const todosEjercicios = obtenerEjerciciosPrecargados();
  return todosEjercicios.filter(e => e.categoria === categoria);
}

/**
 * Obtiene número total de ejercicios precargados
 */
export function obtenerTotalEjerciciosPrecargados(): number {
  return obtenerEjerciciosPrecargados().length;
}

/**
 * Obtiene resumen de ejercicios por categoría
 */
export function obtenerResumenCategorias() {
  return {
    [CategoriaEjercicio.MOVILIDAD]: ejerciciosMovilidad.length,
    [CategoriaEjercicio.FUERZA]: ejerciciosFuerza.length,
    [CategoriaEjercicio.EQUILIBRIO]: ejerciciosEquilibrio.length,
    [CategoriaEjercicio.ESTIRAMIENTO]: ejerciciosEstiramiento.length,
    [CategoriaEjercicio.CARDIO]: ejerciciosCardio.length,
  };
}
