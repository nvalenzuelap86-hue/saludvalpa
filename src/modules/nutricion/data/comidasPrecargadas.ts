export const comidasPrecargadas: ComidaPrecargada[] = [
  ...desayunos,
  ...colaciones,
  ...comidas,
  ...cenas,
];

export function buscarComidasPorCategoria(categoria: ComidaPrecargada['categoria']): ComidaPrecargada[] {
  return comidasPrecargadas.filter(c => c.categoria === categoria);
}

export function buscarComidasPorNombre(termino: string): ComidaPrecargada[] {
  const busqueda = termino.toLowerCase().trim();
  if (!busqueda) return comidasPrecargadas;
  return comidasPrecargadas.filter(c =>
    c.nombre.toLowerCase().includes(busqueda) ||
    (c.descripcion || '').toLowerCase().includes(busqueda) ||
    (c.etiquetas || []).some(tag => tag.toLowerCase().includes(busqueda))
  );
}

export function obtenerComidaPorId(id: string): ComidaPrecargada | undefined {
  return comidasPrecargadas.find(c => c.id === id);
}

export function obtenerComidasAptasPara(condicion: string): ComidaPrecargada[] {
  return comidasPrecargadas.filter(c => (c.aptoPara || []).includes(condicion));
}

export function obtenerComidasSinAlergeno(alergeno: string): ComidaPrecargada[] {
  return comidasPrecargadas.filter(c => !(c.alergenos || []).includes(alergeno));
}

export function obtenerTotalComidasPrecargadas(): number {
  return comidasPrecargadas.length;
}

export function obtenerResumenCategorias(): Record<ComidaPrecargada['categoria'], number> {
  return {
    desayuno: desayunos.length,
    colacion: colaciones.length,
    comida: comidas.length,
    cena: cenas.length,
  };
}